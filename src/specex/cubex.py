def get_spplate_fits(cube_header, spec_header, obj_ids, spec_data,
                     var_data=None, and_mask_data=None, or_mask_data=None,
                     wdisp_data=None, sky_data=None):
    """
    Generate a plate fits file similar to the ones used in SDSS.

    Parameters
    ----------
    cube_header : TYPE
        DESCRIPTION.
    spec_header : TYPE
        DESCRIPTION.
    obj_ids : TYPE
        DESCRIPTION.
    spec_data : TYPE
        DESCRIPTION.
    var_data : TYPE, optional
        DESCRIPTION. The default is None.
    and_mask_data : TYPE, optional
        DESCRIPTION. The default is None.
    or_mask_data : TYPE, optional
        DESCRIPTION. The default is None.
    wdisp_data : TYPE, optional
        DESCRIPTION. The default is None.
    sky_data : TYPE, optional
        DESCRIPTION. The default is None.

    Returns
    -------
    hdul : TYPE
        DESCRIPTION.

    """
    spec_hdu = fits.PrimaryHDU()
    ivar_hdu = fits.ImageHDU()
    andmsk_hdu = fits.ImageHDU()
    ormsk_hdu = fits.ImageHDU()
    wdisp_hdu = fits.ImageHDU()
    tbl_hdu = fits.BinTableHDU()
    sky_hdu = fits.ImageHDU()

    if isinstance(spec_data, np.ma.MaskedArray):
        spec_data = spec_data.filled(np.nan)

    if isinstance(var_data, np.ma.MaskedArray):
        var_data = var_data.filled(np.nan)

    spec_hdu.data = spec_data.T
    spec_hdu.header['PLATEID'] = 0

    try:
        spec_hdu.header['MJD'] = cube_header['MJD']
    except KeyError:
        try:
            spec_hdu.header['MJD'] = cube_header['MJD-OBS']
        except KeyError:
            print(
                "WARNING: no MJD found in the cube metadata, using extraction "
                "time instead!",
                file=sys.stderr
            )
            spec_hdu.header['MJD'] = Time.now().mjd

    # See the following link for COEFF0 and COEFF1 definition
    # https://classic.sdss.org/dr7/products/spectra/read_spSpec.html
    try:
        spec_hdu.header["COEFF0"] = spec_header["COEFF0"]
        spec_hdu.header["COEFF1"] = spec_header["COEFF1"]
    except KeyError:
        print(
            "WARING: wavelength binning of the input cube is not compatible "
            "with boss log10 binning data model.\n        Computing the best "
            "values of COEFF0 and COEFF1 for this wavelengt range...",
            file=sys.stderr
        )
        # Compute coeff0 and coeff1 that best approximate wavelength range
        # of the datacube
        crpix = spec_header["CRPIX3"] - 1
        crval = spec_header["CRVAL3"]
        cd1 = spec_header.get("CD3_3", spec_header.get("CDELT3", 1.0))

        w_end = spec_data.shape[1] - crpix

        coeff0 = np.log10(crval + cd1*(crpix))
        coeff1 = np.log10(1 + (w_end*cd1)/crval) / w_end

        spec_hdu.header['COEFF0'] = coeff0
        spec_hdu.header['COEFF1'] = coeff1

    spec_hdu.header["CRVAL1"] = spec_header["CRVAL3"]
    spec_hdu.header["CD1_1"] = spec_header.get("CD3_3", spec_header.get("CDELT3", 1.0))
    spec_hdu.header["CDELT1"] = spec_header.get("CD3_3", spec_header.get("CDELT3", 1.0))
    spec_hdu.header["CRPIX1"] = spec_header["CRPIX3"]
    spec_hdu.header['BUNIT'] = spec_header['BUNIT']
    spec_hdu.header["CUNIT1"] = spec_header["CUNIT3"]
    spec_hdu.header["CTYPE1"] = spec_header["CTYPE3"]

    if var_data is not None:
        ivar_hdu.data = 1 / var_data.T

    if wdisp_data is None:
        wdisp_hdu.data = np.zeros_like(spec_data.T)
    else:
        wdisp_hdu.data = wdisp_data.T

    info_table = Table()
    info_table.add_column(
        Column(data=obj_ids, name='FIBERID', dtype='>i4')
    )

    tbl_hdu.data = info_table.as_array()

    hdul = fits.HDUList([
        spec_hdu, ivar_hdu, andmsk_hdu, ormsk_hdu, wdisp_hdu, tbl_hdu, sky_hdu
    ])

    return hdul


def get_spsingle_fits(
    main_header,
    spec_wcs_header,
    obj_spectrum,
    spec_hdu_header,
    obj_spectrum_var=None,
    no_nans=False,
    cutout_data=None,
    cutout_wcs=None,
    wavelengths=None
):
    """
    Generate a FITS file containing the spectral data conforming to the IVOA
    Spectrum Data Model (v1.2).

    Parameters
    ----------
    main_header : dict
        Dictionary containing metadata on the spectrum extraction.
    spec_wcs_header : astropy.io.fits.Header object
        Header containing WCS information of the spectrum.
    obj_spectrum : numpy.ndarray
        The extracted flux spectrum.
    spec_hdu_header : astropy.io.fits.Header object
        Header of the HDU containing the original cube spectral data.
    obj_spectrum_var : numpy.ndarray, optional
        The variance of the spectral data.
    no_nans : bool, optional
        If True, NaN values are replaced with zeros or interpolated data.
    cutout_data : numpy.ndarray, optional
        2D image cutout array.
    cutout_wcs : astropy.wcs.WCS, optional
        WCS associated with the cutout image.
    wavelengths : numpy.ndarray, optional
        Wavelength grid corresponding to the spectrum pixels.

    Returns
    -------
    hdul : astropy.io.fits.HDUList object
        The FITS HDUList containing the VO-compliant spectrum.
    """
    my_time = Time.now()
    my_time.format = 'isot'

    if isinstance(obj_spectrum, np.ma.MaskedArray):
        obj_spectrum = obj_spectrum.filled(np.nan)

    if isinstance(obj_spectrum_var, np.ma.MaskedArray):
        obj_spectrum_var = obj_spectrum_var.filled(np.nan)

    # Primary HDU contains IVOA global metadata
    main_hdu = fits.PrimaryHDU()
    main_hdu.header['VOCLASS'] = ('SPECTRUM 1.2', 'IVOA Spectrum Data Model')
    main_hdu.header['VOPUB'] = ('IVOA', 'VO standard publication')
    main_hdu.header['CREATOR'] = (f'specex {sp_ver}', 'Software creating the dataset')

    for key, val in main_header.items():
        try:
            main_hdu.header[key] = val
        except ValueError:
            print(
                f"Invalid value for spec header: {key} = {val}",
                file=sys.stderr
            )

    flux_unit = spec_hdu_header.get('BUNIT', 'adu')
    wave_unit = spec_hdu_header.get('CUNIT3', spec_hdu_header.get('CUNIT1', 'Angstrom'))

    nanmask = np.isnan(obj_spectrum)
    if no_nans:
        obj_spectrum[nanmask] = 0.0
        if obj_spectrum_var is not None:
            obj_spectrum_var[nanmask] = np.nanmax(obj_spectrum_var) * 100.0

    # Compute wavelength grid if not provided
    if wavelengths is None:
        try:
            sp_wcs = wcs.WCS(spec_wcs_header)
            pixel = np.arange(len(obj_spectrum))
            wavelengths = sp_wcs.pixel_to_world(pixel).value
        except Exception:
            crpix3 = spec_hdu_header.get('CRPIX3', 1.0)
            crval3 = spec_hdu_header.get('CRVAL3', 1.0)
            cdelt3 = spec_hdu_header.get('CD3_3', spec_hdu_header.get('CDELT3', 1.0))
            pixel = np.arange(len(obj_spectrum))
            wavelengths = crval3 + (pixel - (crpix3 - 1)) * cdelt3

    # Build binary table according to IVOA Spectrum DM
    cols = [
        fits.Column(
            name='WAVELENGTH',
            format='1D',
            unit=wave_unit,
            array=wavelengths.astype('float64')
        ),
        fits.Column(
            name='FLUX',
            format='1E',
            unit=flux_unit,
            array=obj_spectrum.astype('float32')
        )
    ]

    if obj_spectrum_var is not None:
        stat_err = np.sqrt(np.maximum(obj_spectrum_var, 0))
        cols.append(
            fits.Column(
                name='ERR',
                format='1E',
                unit=flux_unit,
                array=stat_err.astype('float32')
            )
        )

    quality = nanmask.astype('int16')
    cols.append(
        fits.Column(
            name='QUALITY',
            format='1I',
            array=quality
        )
    )

    tbl_hdu = fits.BinTableHDU.from_columns(cols, name='SPECTRUM')
    tbl_hdu.header['UCD1'] = ('em.wl', 'Wavelength UCD')
    tbl_hdu.header['UCD2'] = ('phot.flux.density;em.wl', 'Flux density UCD')
    if obj_spectrum_var is not None:
        tbl_hdu.header['UCD3'] = ('stat.error;phot.flux.density;em.wl', 'Flux error UCD')
        tbl_hdu.header['UCD4'] = ('meta.code.qual', 'Quality flag UCD')
    else:
        tbl_hdu.header['UCD3'] = ('meta.code.qual', 'Quality flag UCD')

    hdu_list = [main_hdu, tbl_hdu]

    # Keep a NAN_MASK ImageHDU for backward compatibility
    hdu_list.append(
        fits.ImageHDU(
            data=nanmask.astype('uint8'),
            name='NAN_MASK'
        )
    )

    if cutout_data is not None:
        cutout_header = fits.Header()
        if cutout_wcs is not None:
            cutout_header = cutout_wcs.to_header()
        hdu_list.append(
            fits.ImageHDU(
                data=cutout_data,
                header=cutout_header,
                name='CUTOUT'
            )
        )

    hdul = fits.HDUList(hdu_list)
    return hdul


def load_specex_file(
    filename: str | os.PathLike[str],
    spec_hdu_index: Optional[int] = None,
    var_hdu_index: Optional[int] = None,
    wd_hdu_index: Optional[int] = None,
    mask_hdu_index: Optional[int] = None,
    smoothing: int = 0
):
    """
    Load a spectrum file generated by specex (or any compatible file).

    Parameters
    ----------
    filename : str
        The path of the fits file containing the spectrum.
    spec_hdu_index : int or str, optional
        The index or name of the HDU containing the flux.
        The default is None.
    var_hdu_index : int or str, optional
        The index or name of the HDU containing the variance.
        The default is None.
    wd_hdu_index : int or str, optional
        The index or name of the HDU containing the resolution curve.
        The default is None.
    mask_hdu_index : int or str, optional
        The index or name of the HDU containing the flux nan mask.
        The default is None.
    smoothing : int, optional
        If greather than zero, the the spectrum is smoothed with a window of
        this size. The default is 0.

    Raises
    ------
    ValueError
        When flux and variance have different shape.

    Returns
    -------
    dict
        A dict containing the following keys:

        * 'id': the ID of the spectrum,
        * 'main_header': the FITS header of the primary HDU,
        * 'wavelength': the wavelengths of the dispersion grid,
        * 'flux': the fluxes,
        * 'variance': the variance of the fluxes,
        * 'r_curve': the resolution curve,
        * 'nan_mask': a mask indicating invalid fluxes,
        * 'flux_units': the units of the fluxes,
        * 'wavelength_units': the units of the wavelengths

    """
    with fits.open(filename) as hdul:
        valid_id_keys = [
            f"{i}{j}"
            for i in ['', 'OBJ', 'OBJ_', 'TARGET', 'TARGET_']
            for j in ['ID', 'NUMBER', 'UID', 'UUID']
        ]

        spec_id = None
        for hdu in hdul:
            for key in valid_id_keys:
                try:
                    spec_id = hdu.header[key]
                except KeyError:
                    continue
                else:
                    break
            if spec_id is not None:
                break

        main_header = get_hdu(
            hdul,
            hdu_index=0,
            valid_names=['PRIMARY', 'primary'],
            msg_index_error="WARNING: No Primary HDU",
            exit_on_errors=False
        ).header.copy()
        spec_hdu = get_hdu(
            hdul,
            hdu_index=spec_hdu_index,
            valid_names=KNOWN_SPEC_EXT_NAMES,
            msg_err_notfound="WARNING: No spectrum HDU",
            exit_on_errors=False
        )
        var_hdu = get_hdu(
            hdul,
            hdu_index=var_hdu_index,
            valid_names=KNOWN_VARIANCE_EXT_NAMES,
            msg_err_notfound="WARNING: No variance HDU",
            exit_on_errors=False
        )

        if var_hdu is None:
            ivar_hdu = get_hdu(
                hdul,
                hdu_index=var_hdu_index,
                valid_names=KNOWN_INVAR_EXT_NAMES,
                msg_err_notfound="WARNING: No inverse variance HDU",
                exit_on_errors=False
            )

        mask_hdu = get_hdu(
            hdul,
            hdu_index=mask_hdu_index,
            valid_names=KNOWN_MASK_EXT_NAMES,
            msg_err_notfound="WARNING: No nan mask HDU",
            exit_on_errors=False
        )

        wd_hdu = get_hdu(
            hdul,
            hdu_index=wd_hdu_index,
            valid_names=KNOWN_RCURVE_EXT_NAMES,
            msg_err_notfound="WARNING: No r curve HDU",
            exit_on_errors=False
        )

        smoothing_window_size = 4*smoothing + 1

        # Check whether spec_hdu is a BinTableHDU (IVOA Spectrum DM) or ImageHDU
        if spec_hdu is not None and isinstance(spec_hdu, fits.BinTableHDU):
            tbl_data = spec_hdu.data
            col_names_upper = [c.name.upper() for c in spec_hdu.columns]

            # Find wavelength column
            for wl_cand in ['WAVELENGTH', 'WAVE', 'LAMBDA', 'SPECTRAL']:
                if wl_cand in col_names_upper:
                    col_name = spec_hdu.columns[col_names_upper.index(wl_cand)].name
                    lam = tbl_data[col_name].astype('float64')
                    wavelength_units = spec_hdu.columns[col_names_upper.index(wl_cand)].unit
                    break
            else:
                lam = None
                wavelength_units = None

            # Find flux column
            for fl_cand in ['FLUX', 'DATA', 'SCI']:
                if fl_cand in col_names_upper:
                    col_name = spec_hdu.columns[col_names_upper.index(fl_cand)].name
                    flux = tbl_data[col_name].copy()
                    flux_units = spec_hdu.columns[col_names_upper.index(fl_cand)].unit
                    break
            else:
                flux = None
                flux_units = None

            if flux is not None and smoothing > 0:
                flux = savgol_filter(flux, smoothing_window_size, 3)
            if flux is not None:
                flux = flux.astype('float32')

            # Find variance / err column
            if 'VARIANCE' in col_names_upper:
                col_name = spec_hdu.columns[col_names_upper.index('VARIANCE')].name
                var = tbl_data[col_name].copy()
            elif 'ERR' in col_names_upper or 'STAT_ERR' in col_names_upper:
                cand = 'ERR' if 'ERR' in col_names_upper else 'STAT_ERR'
                col_name = spec_hdu.columns[col_names_upper.index(cand)].name
                err = tbl_data[col_name].copy()
                var = err ** 2
            else:
                var = None

            if var is not None and smoothing > 0:
                var = savgol_filter(var, smoothing_window_size, 3)
            if var is not None:
                var = var.astype('float32')

            # Find quality / nan mask column
            if 'QUALITY' in col_names_upper:
                col_name = spec_hdu.columns[col_names_upper.index('QUALITY')].name
                flux_nan_mask = tbl_data[col_name] != 0
            elif mask_hdu is not None:
                flux_nan_mask = mask_hdu.data.astype(bool)
            else:
                flux_nan_mask = np.isnan(flux) if flux is not None else None

        elif spec_hdu is None:
            flux = None
            flux_units = None
            lam = None
            wavelength_units = None
            var = None
        else:
            flux = spec_hdu.data.copy()
            spec_wcs = wcs.WCS(spec_hdu.header)
            if smoothing > 0:
                flux = savgol_filter(flux, smoothing_window_size, 3)
            flux = flux.astype('float32')

            pixel = np.arange(len(flux))
            if spec_wcs.has_spectral:
                lam = (
                    spec_wcs.pixel_to_world(pixel)
                    .Angstrom
                    .astype('float32')
                )
            else:
                try:
                    coeff0 = spec_hdu.header["COEFF0"]
                    coeff1 = spec_hdu.header["COEFF1"]
                except KeyError:
                    lam = None
                else:
                    lam = (10**(coeff0 + coeff1*pixel)).astype('float32')

            try:
                flux_units = spec_hdu.header['BUNIT']
            except KeyError:
                flux_units = None

            try:
                wavelength_units = spec_hdu.header['CUNIT1']
            except KeyError:
                wavelength_units = None

            if mask_hdu is None:
                flux_nan_mask = None
            else:
                flux_nan_mask = mask_hdu.data.astype(bool)
                if flux is not None:
                    flux_nan_mask |= np.isnan(flux)

            if var_hdu is None:
                if ivar_hdu is None:
                    var = None
                else:
                    var = 1 / ivar_hdu.data.copy()
                    if smoothing > 0:
                        var = savgol_filter(var, smoothing_window_size, 3)
                    var = var.astype('float32')
            else:
                var = var_hdu.data.copy()
                if smoothing > 0:
                    var = savgol_filter(var, smoothing_window_size, 3)
                var = var.astype('float32')

        if wd_hdu is None:
            wd = None
        else:
            wd = wd_hdu.data.copy()
            if smoothing > 0:
                wd = savgol_filter(wd, smoothing_window_size, 3)
            wd = wd.astype('float32')

        if (
            (flux is not None) and
            (var is not None) and
            flux.shape != var.shape
        ):
            raise ValueError(
                f"'{filename}' - "
                "Spectral data invalid or corruptede: Flux data shape "
                "do not match variance data one!"
            )

    return {
        'id': spec_id,
        'main_header': main_header,
        'wavelength': lam,
        'flux': flux,
        'variance': var,
        'r_curve': wd,
        'nan_mask': flux_nan_mask,
        'flux_units': flux_units,
        'wavelength_units': wavelength_units
    }


def speclist2ez(
    spec_files: Iterable[str],
    spec_hdu_name: str = 'SPECTRUM',
    var_hdu_name: str = 'VARIANCE'
):
    """
    Generate a list of spectra that can be imported into pandora EZ.

    Parameters
    ----------
    spec_files : list of str
        List of file paths.
    spec_hdu_name : str, optional
        The name of the HDU containing the spectral data.
        The default is 'SPECTRUM'.
    var_hdu_name : str, optional
        The name of the HDU containing the variance data.
        The default is 'VARIANCE'.

    Returns
    -------
    txt_data : TYPE
        DESCRIPTION.

    """
    txt_data = ""

    for file in spec_files:
        txt_data += f'{file}[{spec_hdu_name}](1) - '
        txt_data += f'{file}[{var_hdu_name}](1) -\n'
    return txt_data


def specex(options: Optional[list[str]] = None) -> None:
    """
    Run the main program.

    Returns
    -------
    None.

    """

    # Get user input from argument parsers helper
    args = __argshandler(options)
    logging.basicConfig()

    if args.debug:
        logging.getLogger().setLevel(logging.DEBUG)
        if HAS_IPYTHON:
            sys.excepthook = exception_handler

    # Working mode
    mode = None

    if args.catalog is not None:
        catalog_path: Path = Path(args.catalog)

        if not catalog_path.is_file():
            print(f"The catalog '{catalog_path}' does not exits!")
            sys.exit(1)

        if args.cat_format is not None:
            sources: Table = Table.read(catalog_path, format=args.cat_format)
        else:
            try:
                sources = Table.read(catalog_path)
            except IORegistryError:
                try:
                    sources = Table.read(catalog_path, format='ascii')
                except IORegistryError:
                    print(
                        "ERROR: cannot determine the format of the input "
                        "catalog. Try to specify it manually using the "
                        "option --cat-format.",
                        file=sys.stderr
                    )
                    sys.exit(1)

        basename = catalog_path.stem
        pixelscale = units.Quantity(args.cat_pixelscale)
        coord_frame = args.cat_skyframe  # frame of source coordinates
        if str(pixelscale.unit.physical_type) == 'dimensionless':
            pixelscale = pixelscale * units.mas
    elif args.regionfile is not None:
        if not HAS_REGION:
            logging.error(
                "astropy regions package is needed to handle regionfiles!"
            )
            sys.exit(1)
        regionfile_path: Path = Path(args.regionfile)

        if not regionfile_path.is_file():
            print(f"The region file '{regionfile_path}' does not exits!")
            sys.exit(1)

        sources = parse_regionfile(
            str(regionfile_path),
            key_ra=args.key_ra,
            key_dec=args.key_dec,
            key_id='ID' if args.key_id is None else args.key_id,
            file_format=args.cat_format,
        )

        if sources is None:
            logging.error(
                "Cannot load region file data!",
            )
            sys.exit(1)
        coord_frame = 'icrs'
        basename = regionfile_path.stem
        pixelscale = 1.0 * units.arcsec
        mode = 'regions'
    else:
        logging.error(
            "You must provide at least an input catalog or a region file!",
        )
        sys.exit(1)

    # Try to identify the column with object IDs
    if args.key_id is None:
        valid_id_keys = [
            f"{i}{j}"
            for i in ['', 'OBJ', 'OBJ_', 'TARGET', 'TARGET_']
            for j in ['ID', 'NUMBER', 'UID', 'UUID']
        ]

        for key in valid_id_keys:
            if key.lower() in sources.colnames:
                key_id = key.lower()
                break
            elif key.upper() in sources.colnames:
                key_id = key.upper()
                break
        else:
            key_id = None
    else:
        key_id = args.key_id

    cube_path: Path = Path(args.input_cube)
    if not cube_path.is_file():
        logging.error(
            f"The cube '{cube_path}' does not exist!"
        )
        sys.exit(1)

    with (SpectralCube.open(
        cube_path,
        spec_hdu_index=args.spec_hdu,
        var_hdu_index=args.var_hdu,
        mask_hdu_index=args.mask_hdu
    ) as my_cube):
        if my_cube.spec_hdu is None:
            logging.error(
                "Input cube has no spectral HDU!"
            )
            sys.exit(1)

        if args.debug:
            print(f"Flux HDU: {my_cube.spec_hdu.name}")
            if my_cube.var_hdu is not None:
                print(f"Variance HDU: {my_cube.var_hdu.name}")
            if my_cube.mask_hdu is not None:
                print(f"Mask HDU: {my_cube.mask_hdu.name}")

        # Get spectral and celestial WCS from the cube
        celestial_wcs = my_cube.getSpecWCS().celestial
        spectral_wcs = my_cube.getSpecWCS().spectral
        cube_wavelengths = my_cube.get_spectral_axis(units.Angstrom).value

        # If weighting with an external image, read that
        valid_wl_modes = ['none', 'whitelight', 'log-whitelight']
        weight_img: None | np.ndarray = None
        if args.weighting.lower() not in valid_wl_modes:
            if not os.path.isfile(args.weighting):
                logging.error(
                    f"weighting image does not exist '{args.weighting}' "
                )
                sys.exit(1)
            with fits.open(args.weighting) as hdul:
                wimg_hdu = hdul[0]
                wimg_shape = wimg_hdu.data.shape

                if len(wimg_shape) != 2:
                    logging.error(
                        "ERROR: only grayscale images are supported as "
                        "weightmap!"
                    )
                    sys.exit(1)
                elif HAS_REPROJECT:
                    # Reproject the external weight image to the
                    # datacube footprint
                    weight_img, wimg_mask = do_reproject(
                        wimg_hdu, my_cube
                    )

                    weight_img[wimg_mask == 0] = np.nan
                elif wimg_shape != my_cube.spec_hdu.data.shape[1:]:
                    logging.error(
                        "The shape of the external weightmap image does "
                        "not match the datacube and reproject is not "
                        "installed! Use --help for more information."
                    )
                    sys.exit(1)
                else:
                    weight_img = wimg_hdu.data.copy()

        # TODO: we assume here that the distortion across the sky plane is
        #       negligible, but it is very bold assumption.
        #       A more general approach that takes into account also distortion
        #       in function of the position on the sky is needed.
        # Get the pixelscales in arcsec/pixel.
        cube_pixelscale_x, cube_pixelscale_y = [
            units.Quantity(sc_val, u)
            for sc_val, u in zip(
                wcs.utils.proj_plane_pixel_scales(celestial_wcs),
                celestial_wcs.wcs.cunit
            )
        ]

        if args.debug:
            print(
                "Cube X and Y pixelscales are: "
                f"{cube_pixelscale_x.to(units.arcsec)}, "
                f"{cube_pixelscale_y.to(units.arcsec)}",
                file=sys.stderr
            )

        ra_unit = sources[args.key_ra].unit
        if ra_unit is None:
            if args.debug:
                logging.warning(
                    "RA data has no units, assuming values are in degrees!",
                )
            ra_unit = 'deg'

        dec_unit = sources[args.key_dec].unit
        if dec_unit is None:
            if args.debug:
                logging.warning(
                    "DEC data has no units, assuming values are in degrees!",
                )
            dec_unit = 'deg'

        # Get the objects positions in the cube (in pixels)
        obj_sky_coords = SkyCoord(
            sources[args.key_ra], sources[args.key_dec],
            unit=(ra_unit, dec_unit),
            frame=coord_frame
        )

        obj_x, obj_y = wcs.utils.skycoord_to_pixel(
            coords=obj_sky_coords,
            wcs=celestial_wcs
        )

        sources.add_column(obj_x, name='CUBE_X_IMAGE')
        sources.add_column(obj_y, name='CUBE_Y_IMAGE')

        img_height, img_width = my_cube.getSpatialSizePixels()
        yy, xx = np.meshgrid(
            np.arange(img_height),
            np.arange(img_width),
            indexing='ij'
        )

        extracted_data = np.zeros((img_height, img_width))

        # Check if there is a footprint mask in the cube
        if my_cube.mask_hdu is not None:
            # Valid pixels have 0 in standard DQ mask, or 1 in inverted mask
            cube_footprint = np.any(my_cube.mask_hdu.data == 0, axis=0)
            if args.invert_mask:
                cube_footprint = ~cube_footprint
        else:
            cube_footprint = None

        if args.outdir is None:
            outdir = f'{basename}_spectra'
        else:
            outdir = args.outdir

        if not os.path.isdir(outdir):
            os.mkdir(outdir)

        if mode is None:
            if args.mode == 'auto':
                if (
                        args.key_a in sources.colnames and
                        args.key_b in sources.colnames and
                        args.key_kron in sources.colnames
                ):
                    mode = 'kron_ellipse'
                else:
                    mode = 'circular_aperture'
            elif args.mode == 'fixed-aperture':
                mode = 'circular_aperture'
            else:
                mode = args.mode

        print(f"Extracting spectra with strategy '{mode}'", file=sys.stderr)

        cutout_img_data = None
        cutout_img_wcs = None
        if args.cutouts_image is not None:
            with fits.open(args.cutouts_image) as cut_hdul:
                for hdu in cut_hdul:
                    if hdu.data is not None and len(hdu.data.shape) == 2:
                        cutout_img_data = hdu.data.copy()
                        cutout_img_wcs = wcs.WCS(hdu.header)
                        break
        if cutout_img_data is None:
            cutout_img_data = stack(my_cube.spec_hdu.data, average=True)
            cutout_img_wcs = celestial_wcs

        cutout_box_size = args.cutouts_size * units.arcsec

        n_objects = len(sources)
        if args.nspectra:
            n_objects = min(int(args.nspectra), n_objects)

        out_specfiles = []
        specex_apertures = {}  # these values are in physical units (arcsecs)
        source_ids = []

        valid_sources_mask = np.zeros(n_objects, dtype=bool)

        if args.debug:
            print(
                f"Read {len(sources[:n_objects])} sources from "
                "input catalog/regionfile...",
                file=sys.stderr
            )

        try:
            if key_id is not None:
                sources.sort(key_id)
        except KeyError:
            pass

        for i, source in enumerate(sources[:n_objects]):
            simple_pbar_callback(i + 1, n_objects)

            if key_id is not None:
                obj_id = source[key_id]
            else:
                obj_id = f"{i:06}"

            obj_ra = source[args.key_ra]
            obj_dec = source[args.key_dec]
            xx_tr = xx - source['CUBE_X_IMAGE']
            yy_tr = yy - source['CUBE_Y_IMAGE']

            anulus_mask = None
            if mode == 'regions':
                pix_reg = source['region'].to_pixel(celestial_wcs)
                reg_mask = pix_reg.to_mask()
                mask = reg_mask.to_image((img_height, img_width))
                if mask is None:
                    logging.warning(
                        f"object {obj_id} is outside the cube, skipping..."
                    )
                    continue
                mask = mask > 0
                specex_apertures[obj_id] = (
                    1 * pixelscale,
                    1 * pixelscale,
                    0 * units.rad
                )

            elif mode == 'kron_ellipse':
                ang = np.deg2rad(source[args.key_theta])

                # Scale semi-axes from catalog pixelscale to cube pixel scales
                a_pix_x = (source[args.key_a] * pixelscale).to(units.arcsec) / cube_pixelscale_x
                b_pix_y = (source[args.key_b] * pixelscale).to(units.arcsec) / cube_pixelscale_y

                x_over_a = xx_tr*np.cos(ang) + yy_tr*np.sin(ang)
                x_over_a /= a_pix_x.value

                y_over_b = xx_tr*np.sin(ang) - yy_tr*np.cos(ang)
                y_over_b /= b_pix_y.value

                specex_apertures[obj_id] = (
                    2 * source[args.key_a] * source[args.key_kron] * pixelscale,
                    2 * source[args.key_b] * source[args.key_kron] * pixelscale,
                    source[args.key_theta] * units.deg
                )

                r_ell_sq = x_over_a**2 + y_over_b**2
                r_kron = source[args.key_kron]
                mask = r_ell_sq < (r_kron ** 2)

                if args.anulus_size and args.anulus_size.lower() != 'none':
                    try:
                        an_parts = [p.strip() for p in args.anulus_size.split(',')]
                        if any(p.endswith('x') for p in an_parts):
                            k_in = float(an_parts[0].rstrip('x')) * r_kron
                            k_out = float(an_parts[1].rstrip('x')) * r_kron
                        else:
                            r1 = units.Quantity(an_parts[0])
                            r2 = units.Quantity(an_parts[1])
                            k_in = r_kron * (r1 / (source[args.key_a] * pixelscale)).decompose().value
                            k_out = r_kron * (r2 / (source[args.key_a] * pixelscale)).decompose().value
                        anulus_mask = (r_ell_sq >= k_in**2) & (r_ell_sq < k_out**2)
                    except Exception as an_err:
                        if args.debug:
                            logging.warning(f"Invalid anulus_size '{args.anulus_size}': {an_err}")

            elif mode in ('kron_circular', 'kron_circle'):
                kron_circ_rad = (
                    source[args.key_kron] *
                    np.sqrt(source[args.key_a] * source[args.key_b]) *
                    pixelscale
                )

                specex_apertures[obj_id] = (
                    2 * kron_circ_rad,
                    2 * kron_circ_rad,
                    0 * units.rad
                )

                xx_scaled = xx_tr * cube_pixelscale_x
                yy_scaled = yy_tr * cube_pixelscale_y
                r_circ_sq = xx_scaled**2 + yy_scaled**2
                r_circ_val = kron_circ_rad.to(units.arcsec)
                mask = r_circ_sq < (r_circ_val ** 2)

                if args.anulus_size and args.anulus_size.lower() != 'none':
                    try:
                        an_parts = [p.strip() for p in args.anulus_size.split(',')]
                        if any(p.endswith('x') for p in an_parts):
                            k_in = float(an_parts[0].rstrip('x')) * r_circ_val
                            k_out = float(an_parts[1].rstrip('x')) * r_circ_val
                        else:
                            k_in = units.Quantity(an_parts[0]).to(units.arcsec)
                            k_out = units.Quantity(an_parts[1]).to(units.arcsec)
                        anulus_mask = (r_circ_sq >= k_in**2) & (r_circ_sq < k_out**2)
                    except Exception as an_err:
                        if args.debug:
                            logging.warning(f"Invalid anulus_size '{args.anulus_size}': {an_err}")

            elif mode == 'circular_aperture':
                aperture_size = units.Quantity(args.aperture_size)
                aperture_radius = aperture_size / 2
                if str(aperture_size.unit.physical_type) == 'dimensionless':
                    aperture_radius = aperture_radius * units.mas

                try:
                    specex_apertures[obj_id] = (
                        aperture_size if str(aperture_size.unit.physical_type) != 'dimensionless' else aperture_size * units.mas,
                        aperture_size if str(aperture_size.unit.physical_type) != 'dimensionless' else aperture_size * units.mas,
                        0 * units.rad
                    )
                except TypeError:
                    logging.warning(
                        f"object {obj_id} has an invalid ID, skipping..."
                    )
                    continue

                xx_scaled = xx_tr * cube_pixelscale_x
                yy_scaled = yy_tr * cube_pixelscale_y
                r_circ_sq = xx_scaled**2 + yy_scaled**2
                r_aper_val = aperture_radius.to(units.arcsec)
                mask = r_circ_sq < (r_aper_val)**2

                if args.anulus_size and args.anulus_size.lower() != 'none':
                    try:
                        an_parts = [p.strip() for p in args.anulus_size.split(',')]
                        if any(p.endswith('x') for p in an_parts):
                            k_in = float(an_parts[0].rstrip('x')) * r_aper_val
                            k_out = float(an_parts[1].rstrip('x')) * r_aper_val
                        else:
                            k_in = units.Quantity(an_parts[0]).to(units.arcsec)
                            k_out = units.Quantity(an_parts[1]).to(units.arcsec)
                        anulus_mask = (r_circ_sq >= k_in**2) & (r_circ_sq < k_out**2)
                    except Exception as an_err:
                        if args.debug:
                            logging.warning(f"Invalid anulus_size '{args.anulus_size}': {an_err}")

            if anulus_mask is not None:
                anulus_mask &= ~mask
                if cube_footprint is not None:
                    anulus_mask &= cube_footprint

            if cube_footprint is not None:
                mask &= cube_footprint

            if np.sum(mask) == 0:
                logging.warning(
                    f"object {obj_id} has no footprint, skipping..."
                )
                continue

            obj_extraction_mask = np.zeros_like(mask, dtype='float32')
            if args.weighting.lower() == 'none':
                weights = None
                obj_extraction_mask[mask] = 1.0
            else:
                if args.weighting.lower() == 'whitelight':
                    # summing selected spaxels along spectral axis to get a
                    # whitelight weightmap
                    w_arr = np.ma.array(
                        my_cube.spec_hdu.data[:, mask],
                        mask=~np.isfinite(my_cube.spec_hdu.data[:, mask]),
                        dtype='float32'
                    )
                    weights = np.ma.mean(w_arr, axis=0)
                    w_min = np.ma.min(weights)
                    w_max = np.ma.max(weights)
                    if w_max > w_min:
                        weights -= w_min
                    else:
                        weights = np.ones_like(weights)
                elif args.weighting.lower() == 'log-whitelight':
                    w_arr = np.ma.array(
                        my_cube.spec_hdu.data[:, mask],
                        mask=~np.isfinite(my_cube.spec_hdu.data[:, mask]),
                        dtype='float32'
                    )
                    weights = np.ma.mean(w_arr, axis=0)
                    w_min = np.ma.min(weights)
                    w_max = np.ma.max(weights)
                    if w_max > w_min:
                        weights = np.ma.log10(1 + (weights - w_min))
                    else:
                        weights = np.ones_like(weights)
                elif weight_img is not None:
                    weights = np.ma.masked_invalid(weight_img[mask])
                    w_min = np.ma.min(weights)
                    w_max = np.ma.max(weights)
                    if w_max > w_min:
                        weights -= w_min
                    else:
                        weights = np.ones_like(weights)

                obj_extraction_mask[mask] = weights

            var_spaxels = None
            if my_cube.var_hdu is not None:
                var_spaxels = my_cube.var_hdu.data[:, mask]

            obj_spectrum, obj_spectrum_var = get_spectrum(
                flux_spaxels=my_cube.spec_hdu.data[:, mask],
                var_spaxels=var_spaxels,
                weights=weights
            )

            valid_pixels = np.isfinite(obj_spectrum)
            valid_pixels &= np.isfinite(obj_spectrum_var)
            obj_spectrum[~valid_pixels] = np.nan
            obj_spectrum_var[~valid_pixels] = np.nan

            if np.sum(np.isfinite(obj_spectrum)) / len(obj_spectrum) < 0.5:
                logging.warning(
                    f"WARNING: object {obj_id} has invalid data..."
                )

            if anulus_mask is not None and np.sum(anulus_mask) > 0:
                # Estimate robust median background spectrum across the annulus
                bkg_spaxels = my_cube.spec_hdu.data[:, anulus_mask]
                bkg_spectrum = np.nanmedian(bkg_spaxels, axis=1)

                # Effective area / scale factor of background in object aperture
                n_mask_pix = np.sum(mask)
                if weights is not None:
                    # In weighted extraction, the background scales with the sum of weights
                    scale_bkg = float(np.sum(weights))
                else:
                    scale_bkg = float(n_mask_pix)

                obj_spectrum -= bkg_spectrum * scale_bkg

                # Estimate per-channel background error and propagate to variance
                n_bkg_pix = np.sum(anulus_mask)
                bkg_mad = np.array([
                    nannmad(bkg_spaxels[ch, :]) for ch in range(bkg_spaxels.shape[0])
                ])
                bkg_err_median = 1.2533 * bkg_mad / np.sqrt(max(1, n_bkg_pix))
                obj_spectrum_var += (scale_bkg * bkg_err_median) ** 2

            if np.sum(np.isfinite(obj_spectrum)) == 0:
                if args.debug:
                    logging.warning(
                        f"WARNING: object {obj_id} has no spectral data, "
                        "skipping..."
                    )
                continue

            sn_spec = get_spectrum_snr(obj_spectrum, obj_spectrum_var)
            sn_em = get_spectrum_snr_emission(obj_spectrum, obj_spectrum_var)

            if (
                    (args.sn_threshold > 0) and
                    (max(sn_spec, sn_em) < args.sn_threshold)
               ):

                if args.debug:
                    logging.warning(
                        f"WARNING: object {obj_id} has SNR={sn_spec:.2f} < "
                        f"{args.sn_threshold}, skipping..."
                    )
                continue

            my_time = Time.now()
            my_time.format = 'isot'

            if args.out_name is None:
                outname = f"spec_{obj_id}.fits"
            else:
                outname = args.out_name.replace('%d', str(obj_id))
                try:
                    outname = outname.format(**source)
                except KeyError as exc:
                    logging.error(
                        f"ERROR: output name formatting error: {exc}"
                    )

            apertures_info = [
                x.to_string() for x in specex_apertures[obj_id]
            ]

            main_header = {
                'CUBE': (
                    cube_path.name, "Spectral cube used for extraction"
                ),
                'RA': (
                    obj_ra, "Ra of the center of the object"
                ),
                'DEC': (
                    obj_dec, "Dec of the center of the object"
                ),
                'FRAME': (
                    coord_frame, "Ra and Dec sky frame"
                ),
                'NPIX': (
                    np.sum(mask), 'Number of pixels used for this spectra'
                ),
                'HISTORY': f'Extracted with specex {sp_ver} on {str(my_time)}',
                'ID': obj_id,
                'SN': (
                    sn_spec, "SNR of the total spectrum"
                ),
                'SN_EMISS': (
                    sn_em, "SNR due to emission lines only"
                ),
                'EXT_MODE': (
                    mode, "Spex extraction mode"
                ),
                'EXT_APER': (
                    json.dumps(apertures_info),
                    "Apertures used in specex"
                )
            }

            # Copy the spectral part of the WCS into the new FITS
            spec_wcs_header = spectral_wcs.to_header()

            obj_cutout_dict = None
            try:
                obj_cutout_dict = get_gray_cutout(
                    cutout_img_data,
                    center=SkyCoord(obj_ra, obj_dec, unit='deg', frame=coord_frame),
                    size=cutout_box_size,
                    data_wcs=cutout_img_wcs
                )
            except Exception as cut_err:
                if args.debug:
                    logging.warning(f"Could not extract cutout for {obj_id}: {cut_err}")

            hdul = get_spsingle_fits(
                main_header, spec_wcs_header,
                obj_spectrum, my_cube.spec_hdu.header,
                obj_spectrum_var, no_nans=args.no_nans,
                cutout_data=obj_cutout_dict['data'] if obj_cutout_dict else None,
                cutout_wcs=obj_cutout_dict['wcs'] if obj_cutout_dict else None,
                wavelengths=cube_wavelengths
            )

            out_file_name = os.path.join(outdir, outname)
            hdul.writeto(
                out_file_name,
                overwrite=True
            )

            # If we arrived here, then the object has a vail spectrum and can
            # be saved. Let's also mark the object as valid and store its ID
            out_specfiles.append(os.path.realpath(out_file_name))
            source_ids.append(obj_id)
            valid_sources_mask[i] = True

            # Add also the extracted pixels to the extraction map
            extracted_data += obj_extraction_mask
            if anulus_mask is not None:
                extracted_data -= anulus_mask

        # Discard all invalid sources
        sources = sources[:n_objects][valid_sources_mask]
        source_ids = np.array(source_ids)

        ez_list_file = os.path.join(outdir, "spec_list_pandora_ez.txt")
        with open(ez_list_file, 'w') as f:
            f.write(speclist2ez(out_specfiles))

        if args.debug:
            print(
                f"\nExtracted {len(sources)} valid sources\n",
                file=sys.stderr
            )

        if args.checkimg_outdir is not None:
            check_images_outdir = args.checkimg_outdir
        else:
            check_images_outdir = os.path.join(outdir, 'checkimages')

        if not os.path.isdir(check_images_outdir):
            os.mkdir(check_images_outdir)

        if args.debug:
            stacked_cube = stack(my_cube.spec_hdu.data)
            fig = plt.figure(figsize=(10, 10))
            ax = plt.subplot(projection=celestial_wcs)
            logimg, cvmin, cvmax = get_log_img(stacked_cube)
            ax.imshow(
                logimg,
                origin='lower',
                vmin=cvmin,
                vmax=cvmax,
                cmap='jet'
            )
            stacked_cube_png = os.path.join(check_images_outdir, "stacked_cube.png")
            fig.savefig(stacked_cube_png)
            plt.tight_layout()
            plt.close(fig)

        specex_map = fits.PrimaryHDU(
            data=extracted_data,
            header=celestial_wcs.to_header()
        )
        extmap_path = os.path.join(outdir, f"{my_cube.filename.stem}_extmap.fits")
        specex_map.writeto(
            extmap_path,
            overwrite=True
        )

        if args.check_images:
            fig, ax = plt.subplots(1, 1, figsize=(10, 10))
            ax.imshow(extracted_data, origin='lower')
            extmap_png = os.path.join(check_images_outdir, "sext_extraction_map.png")
            fig.savefig(extmap_png, dpi=150)
            plt.close(fig)


if __name__ == '__main__':
    specex()
